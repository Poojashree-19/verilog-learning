`timescale 1ns/1ps

module alu_control_tb;

    // Testbench Signals

    logic [1:0] ALUOp;
    logic [2:0] funct3;
    logic [6:0] funct7;

    logic [3:0] alu_control;

    // DUT

    alu_control dut (

        .ALUOp(ALUOp),
        .funct3(funct3),
        .funct7(funct7),
        .alu_control(alu_control)

    );

    // Monitor

    initial begin
        $monitor("Time=%0t | ALUOp=%b | funct3=%b | funct7=%b | ALU_Control=%b",
                 $time, ALUOp, funct3, funct7, alu_control);
    end

    // Test Cases

    initial begin

        $dumpfile("alu_control.vcd");
        $dumpvars(0, alu_control_tb);

        $display("======================================");
        $display("Starting ALU Control Test");
        $display("======================================");

        // -----------------------------------------
        // Test Case 1 : LW / SW (ADD)
        // -----------------------------------------
        ALUOp  = 2'b00;
        funct3 = 3'b000;
        funct7 = 7'b0000000;
        #10;

        // -----------------------------------------
        // Test Case 2 : BEQ (SUB)
        // -----------------------------------------
        ALUOp  = 2'b01;
        #10;

        // -----------------------------------------
        // Test Case 3 : ADD
        // -----------------------------------------
        ALUOp  = 2'b10;
        funct3 = 3'b000;
        funct7 = 7'b0000000;
        #10;

        // -----------------------------------------
        // Test Case 4 : SUB
        // -----------------------------------------
        funct7 = 7'b0100000;
        #10;

        // -----------------------------------------
        // Test Case 5 : AND
        // -----------------------------------------
        funct3 = 3'b111;
        funct7 = 7'b0000000;
        #10;

        // -----------------------------------------
        // Test Case 6 : OR
        // -----------------------------------------
        funct3 = 3'b110;
        #10;

        // -----------------------------------------
        // Test Case 7 : XOR
        // -----------------------------------------
        funct3 = 3'b100;
        #10;

        // -----------------------------------------
        // Test Case 8 : SLL
        // -----------------------------------------
        funct3 = 3'b001;
        #10;

        // -----------------------------------------
        // Test Case 9 : SRL
        // -----------------------------------------
        funct3 = 3'b101;
        funct7 = 7'b0000000;
        #10;

        // -----------------------------------------
        // Test Case 10 : SRA
        // -----------------------------------------
        funct7 = 7'b0100000;
        #10;

        // -----------------------------------------
        // Test Case 11 : SLT
        // -----------------------------------------
        funct3 = 3'b010;
        funct7 = 7'b0000000;
        #10;

        // -----------------------------------------
        // Test Case 12 : SLTU
        // -----------------------------------------
        funct3 = 3'b011;
        #10;

        // -----------------------------------------
        // Test Case 13 : ADDI
        // -----------------------------------------
        ALUOp  = 2'b11;
        funct3 = 3'b000;
        funct7 = 7'b0000000;
        #10;

        $display("======================================");
        $display("ALU Control Test Completed");
        $display("======================================");

        $finish;

    end

endmodule
